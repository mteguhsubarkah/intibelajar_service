"""Reproducible extraction of the Slice 2 migration (M3) from the authoritative DDL in 04.

From 04 §4: `diagnosis_report`, verbatim. From 04 §2: the `job.diagnosis_run_id` column. 04 §9 says `job` gains one
reference column per slice and its num_nonnulls check is replaced each time; 0001 created that check unnamed, so it
is found by definition and replaced by a named one. Appended: 04 §5 indexes and a guard on report resolution.
"""
from pathlib import Path
import re

source = Path('docs/backend-architecture/04-postgresql-erd.md').read_text(encoding='utf8')
learning = next(b for b in re.findall(r'```sql\n(.*?)```', source, re.S) if 'CREATE TABLE learning_session' in b)
report = re.search(r'CREATE TABLE diagnosis_report \(.*?\n\);\n', learning, re.S).group(0)
platform = next(b for b in re.findall(r'```sql\n(.*?)```', source, re.S) if 'CREATE TABLE job (' in b)
column = re.search(r'^\s*(diagnosis_run_id\s+uuid UNIQUE REFERENCES diagnosis_run\(id\)),', platform, re.M).group(1)

up = f'''-- Slice 2 M3: dispute reports and diagnosis jobs, extracted from architecture 04 (§4 diagnosis_report, §2 job).
-- Generated by scripts/extract-migration-question-loop.py; do not edit by hand.
{report}
ALTER TABLE job ADD COLUMN {re.sub(r"\s+", " ", column)};

-- 04 §9: one reference per job; the Slice 0 check (deletion only) is replaced, by definition since it was unnamed.
DO $$
DECLARE c record;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint WHERE conrelid = 'job'::regclass AND contype = 'c'
      AND pg_get_constraintdef(oid) = 'CHECK ((deletion_request_id IS NOT NULL))' LOOP
    EXECUTE format('ALTER TABLE job DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;
ALTER TABLE job ADD CONSTRAINT job_one_target CHECK (num_nonnulls(diagnosis_run_id, deletion_request_id) = 1);

-- 04 §5: staff review queue, erasure by learner, resolution lookups.
CREATE INDEX diagnosis_report_open ON diagnosis_report(created_at) WHERE status = 'OPEN';
CREATE INDEX diagnosis_report_learner ON diagnosis_report(learner_id);
CREATE INDEX diagnosis_report_resolution ON diagnosis_report(resolution_run_id) WHERE resolution_run_id IS NOT NULL;

-- 06 §9.3: a report is resolved once (OPEN -> UPHELD | REJECTED) and is otherwise immutable. The learner's note may be
-- cleared at any time (04 §8 retention: 30 days after resolution, at most 180 days). Deletes stay possible for erasure.
CREATE FUNCTION diagnosis_report_resolve_once() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW) - 'note') = (to_jsonb(OLD) - 'note') AND NEW.note IS NULL THEN RETURN NEW; END IF;
  IF OLD.status = 'OPEN' AND NEW.status IN ('UPHELD', 'REJECTED')
     AND (to_jsonb(NEW) - 'status' - 'resolution_code' - 'resolution_run_id' - 'resolved_at' - 'note')
       = (to_jsonb(OLD) - 'status' - 'resolution_code' - 'resolution_run_id' - 'resolved_at' - 'note')
     AND NEW.note IS NOT DISTINCT FROM OLD.note THEN RETURN NEW; END IF;
  RAISE EXCEPTION 'report % is resolved once and is otherwise immutable', OLD.id USING ERRCODE = 'integrity_constraint_violation';
END $$;
CREATE TRIGGER diagnosis_report_resolve_once BEFORE UPDATE ON diagnosis_report FOR EACH ROW EXECUTE FUNCTION diagnosis_report_resolve_once();
'''
down = '''-- Development rollback only; removes dispute reports and diagnosis jobs.
DELETE FROM job WHERE diagnosis_run_id IS NOT NULL;
ALTER TABLE job DROP CONSTRAINT job_one_target;
ALTER TABLE job DROP COLUMN diagnosis_run_id;
ALTER TABLE job ADD CHECK (deletion_request_id IS NOT NULL);
DROP TABLE diagnosis_report;
DROP FUNCTION diagnosis_report_resolve_once();
'''
Path('migrations/0004_question_loop.up.sql').write_text(up, encoding='utf8', newline='\n')
Path('migrations/0004_question_loop.down.sql').write_text(down, encoding='utf8', newline='\n')
print('wrote 0004_question_loop')
